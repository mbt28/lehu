#!/usr/bin/env python3
"""Write the Yocto recipe's crate list from Cargo.lock.

    packaging/yocto/update-crates.py

Rewrites meta-lehu/recipes-lehu/lehu/lehu-crates.inc: every crates.io
package of the lock file as a crate:// fetch with its checksum, in the
format of `bitbake -c update_crates`. Run it whenever Cargo.lock changes.
"""
import pathlib
import tomllib

root = pathlib.Path(__file__).resolve().parents[2]
lock = tomllib.loads((root / "Cargo.lock").read_text())
crates = [
    (p["name"], p["version"], p["checksum"])
    for p in lock["package"]
    if p.get("source", "").startswith("registry+") and "checksum" in p
]

lines = ["# Autogenerated with 'bitbake -c update_crates lehu'", "", "# from Cargo.lock", 'SRC_URI += " \\']
lines += [f"    crate://crates.io/{name}/{version} \\" for name, version, _ in crates]
lines.append('"')
lines.append("")
lines += [f'SRC_URI[{name}-{version}.sha256sum] = "{checksum}"' for name, version, checksum in crates]
out = root / "packaging/yocto/meta-lehu/recipes-lehu/lehu/lehu-crates.inc"
out.write_text("\n".join(lines) + "\n")
print(f"{out.relative_to(root)}: {len(crates)} crates")
